PLData.guideFor = function (title) {
  const t = String(title || '');
  const keys = Object.keys(PLData.guides);
  for (let i = 0; i < keys.length; i++) {
    if (t.indexOf(keys[i]) >= 0) return PLData.guides[keys[i]];
  }
  return PLData.fallbackGuide;
};

